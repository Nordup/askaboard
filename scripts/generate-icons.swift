#!/usr/bin/env swift

// Turns design/icons.json — the verbatim Paper export — into
// MathTutor/DesignSystem/Generated/IconPaths.swift.
//
//   swift scripts/generate-icons.swift            # writes the default paths
//   swift scripts/generate-icons.swift in.json out.swift
//
// The transform between the sentinels below is mirrored verbatim in
// MathTutorTests/IconTests.swift, which re-runs it in-process and fails if the
// checked-in Swift no longer matches the JSON. A test asserts the two copies are
// textually identical, so the mirror cannot rot unnoticed.

import Foundation

// MARK: - generator core (BEGIN mirrored region)

struct IconSpecFile: Decodable {
    struct Source: Decodable {
        let file: String
        let fileId: String
        let artboards: [String]
        let prose: [String]
    }

    struct Coverage: Decodable {
        struct Exclusion: Decodable {
            let name: String
            let reason: String
        }
        let productGlyphs: Int
        let excluded: [Exclusion]
    }

    struct Normalisation: Decodable {
        struct Exception: Decodable {
            let name: String
            let effectiveStrokeWidth: Double
            let reason: String
        }
        let targetEffectiveStrokeWidth: Double
        let rule: String
        let exceptions: [Exception]
    }

    let source: Source
    let coverage: Coverage
    let normalisation: Normalisation
    let icons: [IconSpec]
}

struct IconSpec: Decodable {
    struct ViewBox: Decodable {
        let width: Double
        let height: Double
    }

    struct Anomaly: Decodable {
        let instance: String
        let renderSize: Double
        let designStrokeWidth: Double
        let effectiveStrokeWidth: Double
        let note: String
    }

    let name: String
    let swiftCase: String
    let viewBox: ViewBox
    let productRenderSizes: [Double]
    let renderSize: Double
    let effectiveStrokeWidth: Double?
    let colorToken: String
    let dashTexture: String?
    let notes: String
    let designAnomaly: Anomaly?
    let elements: [IconElementSpec]
}

struct IconElementSpec: Decodable {
    let type: String
    let d: String?
    let x: Double?
    let y: Double?
    let width: Double?
    let height: Double?
    let rx: Double?
    let cx: Double?
    let cy: Double?
    let r: Double?
    let fill: String
    let stroke: String
    let strokeWidth: Double?
    let lineCap: String?
    let lineJoin: String?
    let dashArray: [Double]?
}

enum IconGenerator {
    /// The board's two named dash textures, mapped to the Swift cases that carry them.
    /// A texture absent from this table is a texture the port does not know about, and
    /// the generator refuses rather than dropping it silently.
    static let textures: [String: String] = [
        "dash/dotted": ".dotted",
        "dash/marching": ".marching",
    ]

    /// SVG's defaults, spelled out. An undeclared cap is `butt` and an undeclared join
    /// is `miter` — the design relies on both, so neither can be left to inference.
    static let caps: [String: String] = ["butt": ".butt", "round": ".round", "square": ".square"]
    static let joins: [String: String] = ["miter": ".miter", "round": ".round", "bevel": ".bevel"]

    enum Failure: Error, CustomStringConvertible {
        case unknownElement(String)
        case unknownTexture(String)
        case unknownLineStyle(String)

        var description: String {
            switch self {
            case .unknownElement(let type): "unknown element type \"\(type)\""
            case .unknownTexture(let name): "unknown dash texture \"\(name)\""
            case .unknownLineStyle(let name): "unknown cap or join \"\(name)\""
            }
        }
    }

    static func swiftSource(from data: Data) throws -> String {
        let file = try JSONDecoder().decode(IconSpecFile.self, from: data)
        var out = header(for: file)
        for icon in file.icons {
            let glyph = try declaration(for: icon, in: file)
            out += "\n" + glyph + "\n"
        }
        out += "\n" + dispatch(for: file) + "}\n"
        return out
    }

    static func header(for file: IconSpecFile) -> String {
        var out = """
        // Generated by scripts/generate-icons.swift — do not edit by hand.
        //
        // Source:   Paper file "\(file.source.file)"
        //           \(file.source.fileId)
        //
        """
        out += "\n"
        for artboard in file.source.artboards {
            out += wrap(artboard, prefix: "//           ")
        }
        out += "// Glyphs:   \(file.coverage.productGlyphs) product glyphs.\n"
        out += "// Prose:    \(file.source.prose.joined(separator: "\n//           "))\n"
        out += "//\n// Not here:\n"
        for exclusion in file.coverage.excluded {
            out += "//   \(exclusion.name)\n"
            out += wrap(exclusion.reason, prefix: "//     ")
        }
        out += """
        //
        // The `d` strings are the design's own, character for character, so this file can be
        // diffed straight against the Paper markup. Nothing here was redrawn, rounded, or
        // tidied; where a coordinate looks odd it is odd in the design too.
        //
        // The types live in Icon.swift. This file is data.

        import CoreGraphics

        enum IconPaths {

        """
        return out
    }

    static func declaration(for icon: IconSpec, in file: IconSpecFile) throws -> String {
        var out = wrap(headline(for: icon), prefix: "    /// ")
        out += "    ///\n"
        out += wrap(icon.notes, prefix: "    /// ")
        out += "    static let \(icon.swiftCase) = IconGlyph(\n"
        out += "        name: \(quoted(icon.name)),\n"
        out += "        viewBox: CGSize(width: \(number(icon.viewBox.width)), "
        out += "height: \(number(icon.viewBox.height))),\n"
        out += "        renderSize: \(number(icon.renderSize)),\n"
        out += "        productRenderSizes: [\(icon.productRenderSizes.map(number).joined(separator: ", "))],\n"

        if let exception = file.normalisation.exceptions.first(where: { $0.name == icon.name }) {
            out += wrap(
                "Exception to the \(decimal(file.normalisation.targetEffectiveStrokeWidth)) rule, "
                    + "kept deliberately. \(exception.reason)",
                prefix: "        // "
            )
        }
        var weight = icon.effectiveStrokeWidth
        if weight == nil {
            out += wrap("Nothing is stroked here, so this value is never read.", prefix: "        // ")
            weight = file.normalisation.targetEffectiveStrokeWidth
        }
        out += "        strokeWidth: \(number(weight ?? 0)),\n"
        out += "        colorToken: \(quoted(icon.colorToken)),\n"
        out += anomaly(for: icon)
        out += "        elements: [\n"
        for element in icon.elements {
            out += try declaration(for: element, texture: icon.dashTexture)
        }
        out += "        ]\n"
        out += "    )\n"
        return out
    }

    /// The one-line summary that opens each glyph's doc comment.
    static func headline(for icon: IconSpec) -> String {
        var sizes = "renders \(number(icon.renderSize))"
        if icon.productRenderSizes.count > 1 {
            let drawn = icon.productRenderSizes.map(number).joined(separator: ", ")
            sizes += " (product draws it at \(drawn))"
        }
        let weight = icon.effectiveStrokeWidth.map { "\(decimal($0))pt effective stroke" } ?? "fill only"
        return "`\(icon.name)` — \(sizes) on a \(number(icon.viewBox.width))×"
            + "\(number(icon.viewBox.height)) viewBox, \(weight), \(icon.colorToken)."
    }

    /// A defect in the design, carried into the code rather than quietly corrected.
    /// Recording it is what lets a test pin the current value, so that fixing it
    /// upstream shows up as a failing expectation instead of a silent change.
    static func anomaly(for icon: IconSpec) -> String {
        guard let anomaly = icon.designAnomaly else { return "" }
        var out = "        designAnomaly: IconAnomaly(\n"
        out += "            instance: \(quoted(anomaly.instance)),\n"
        out += "            renderSize: \(number(anomaly.renderSize)),\n"
        out += "            designStrokeWidth: \(number(anomaly.designStrokeWidth)),\n"
        out += "            effectiveStrokeWidth: \(number(anomaly.effectiveStrokeWidth)),\n"
        out += "            note: \(quoted(anomaly.note))\n"
        out += "        ),\n"
        return out
    }

    static func declaration(for element: IconElementSpec, texture: String?) throws -> String {
        var out = "            IconElement(\n"
        out += "                geometry: \(try geometry(of: element)),\n"
        out += "                isFilled: \(element.fill != "none"),\n"
        out += "                isStroked: \(element.stroke != "none"),\n"
        out += "                lineCap: \(try style(element.lineCap, in: caps, default: "butt")),\n"
        out += "                lineJoin: \(try style(element.lineJoin, in: joins, default: "miter")),\n"
        out += "                dash: \(try dash(of: element, texture: texture)),\n"
        out += "                designStrokeWidth: \(element.strokeWidth.map(number) ?? "nil")\n"
        out += "            ),\n"
        return out
    }

    static func geometry(of element: IconElementSpec) throws -> String {
        switch element.type {
        case "path":
            return ".path(\(quoted(element.d ?? "")))"
        case "rect":
            return ".rect(x: \(number(element.x ?? 0)), y: \(number(element.y ?? 0)), "
                + "width: \(number(element.width ?? 0)), height: \(number(element.height ?? 0)), "
                + "cornerRadius: \(number(element.rx ?? 0)))"
        case "circle":
            return ".circle(centerX: \(number(element.cx ?? 0)), centerY: \(number(element.cy ?? 0)), "
                + "radius: \(number(element.r ?? 0)))"
        default:
            throw Failure.unknownElement(element.type)
        }
    }

    static func dash(of element: IconElementSpec, texture: String?) throws -> String {
        guard element.dashArray != nil else { return "nil" }
        guard let texture, let swiftCase = textures[texture] else {
            throw Failure.unknownTexture(texture ?? "none declared on the glyph")
        }
        return swiftCase
    }

    static func style(_ declared: String?, in table: [String: String], default fallback: String) throws -> String {
        let name = declared ?? fallback
        guard let swiftCase = table[name] else { throw Failure.unknownLineStyle(name) }
        return swiftCase
    }

    static func dispatch(for file: IconSpecFile) -> String {
        var out = """
            /// Every glyph, by case.
            ///
            /// A switch and not a dictionary: adding a case to `Icon` without adding its
            /// geometry here fails the build rather than rendering a blank slot.
            static func glyph(for icon: Icon) -> IconGlyph {
                switch icon {

        """
        for icon in file.icons {
            out += "        case .\(icon.swiftCase): Self.\(icon.swiftCase)\n"
        }
        out += "        }\n    }\n"
        return out
    }

    /// `28.0` -> `28`, `2.18` -> `2.18`. Swift reads an integral literal as a `CGFloat`
    /// happily, and a trailing `.0` on every coordinate would bury the ones that matter.
    static func number(_ value: Double) -> String {
        value == value.rounded() ? String(Int(value)) : String(value)
    }

    /// One decimal place, for prose where `2` would read as an integer count rather than
    /// a stroke weight.
    static func decimal(_ value: Double) -> String {
        String(format: "%.1f", value)
    }

    static func quoted(_ text: String) -> String {
        "\"" + text.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\""
    }

    /// Hard-wraps to 96 columns so long rationales stay readable in the generated file.
    /// Deterministic: greedy, on spaces, no hyphenation.
    static func wrap(_ text: String, prefix: String, width: Int = 96) -> String {
        var lines: [String] = []
        var line = ""
        for word in text.split(separator: " ") {
            let candidate = line.isEmpty ? String(word) : line + " " + word
            if prefix.count + candidate.count > width, !line.isEmpty {
                lines.append(line)
                line = String(word)
            } else {
                line = candidate
            }
        }
        if !line.isEmpty { lines.append(line) }
        return lines.map { prefix + $0 + "\n" }.joined()
    }
}

// MARK: - generator core (END mirrored region)

let repoRoot = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
let arguments = Array(CommandLine.arguments.dropFirst())
let input = arguments.count > 0
    ? URL(fileURLWithPath: arguments[0])
    : repoRoot.appendingPathComponent("design/icons.json")
let output = arguments.count > 1
    ? URL(fileURLWithPath: arguments[1])
    : repoRoot.appendingPathComponent("MathTutor/DesignSystem/Generated/IconPaths.swift")

do {
    let source = try IconGenerator.swiftSource(from: Data(contentsOf: input))
    try FileManager.default.createDirectory(
        at: output.deletingLastPathComponent(),
        withIntermediateDirectories: true
    )
    try source.write(to: output, atomically: true, encoding: .utf8)
    print("wrote \(output.path)")
} catch {
    FileHandle.standardError.write(Data("generate-icons: \(error)\n".utf8))
    exit(1)
}
