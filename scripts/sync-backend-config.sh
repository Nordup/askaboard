#!/usr/bin/env bash
# Write MathTutor/Config/Backend.local.xcconfig from .env.local (or the
# environment), so the device token is compiled into the app rather than
# injected at launch.
#
# Why a build setting and not a launch environment variable: launch injection
# only works when something launches the app *with* those variables — Xcode,
# `devicectl`, `scripts/run-sim.sh`. Tap the icon on the Home screen and there
# is no launching process to set them, in Debug or Release. A build the user
# taps has to already contain its credential.
#
# The written file is gitignored and is the only place in the repo tree the
# token lands. Run this before `xcodebuild` — `run-sim.sh` does it for you.
#
# The base URL is not written here: it is a constant in BackendConfiguration.
# See the note in Backend.xcconfig for why an xcconfig cannot hold a URL.
#
# Usage:
#   scripts/sync-backend-config.sh
#   MATHTUTOR_BACKEND_TOKEN=... scripts/sync-backend-config.sh
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="${ROOT}/.env.local"
OUT="${ROOT}/MathTutor/Config/Backend.local.xcconfig"

# The caller's environment wins over the file, so a one-off override does not
# need the file edited. Captured before sourcing, because `set -a; source`
# would otherwise overwrite it.
ENV_TOKEN="${MATHTUTOR_BACKEND_TOKEN:-}"

if [[ -f "$ENV_FILE" ]]; then
  set -a
  # shellcheck source=/dev/null
  source "$ENV_FILE"
  set +a
fi

TOKEN="${ENV_TOKEN:-${MATHTUTOR_BACKEND_TOKEN:-}}"

if [[ -z "$TOKEN" ]]; then
  cat >&2 <<EOF
No device token found.

Create ${ENV_FILE} containing:

  MATHTUTOR_BACKEND_TOKEN=...   # matches the server's DEVICE_TOKEN

That file is gitignored. Alternatively export MATHTUTOR_BACKEND_TOKEN yourself.
EOF
  exit 1
fi

# An xcconfig value runs to end of line and "//" starts a comment anywhere on
# it, so a token containing one would be silently truncated and ship as a
# confusing 401. Refuse instead.
if [[ "$TOKEN" == *"//"* ]]; then
  echo "The token contains '//', which xcconfig reads as a comment. Refusing to write a truncated value." >&2
  exit 1
fi

mkdir -p "$(dirname "$OUT")"
cat > "$OUT" <<EOF
// Generated by scripts/sync-backend-config.sh — do not edit, do not commit.
// Gitignored: this is the one place in the repo tree the device token lands.
MATHTUTOR_BACKEND_TOKEN = ${TOKEN}
EOF

echo "==> Wrote ${OUT#"$ROOT"/} (token ${#TOKEN} chars)"
