#!/usr/bin/env swift

// Turns design/tokens.json — the verbatim Paper export — into
// MathTutor/DesignSystem/Generated/DesignTokens.swift.
//
//   swift scripts/generate-tokens.swift            # writes the default paths
//   swift scripts/generate-tokens.swift in.json out.swift
//
// The transform between the sentinels below is mirrored verbatim in
// MathTutorTests/DesignSystemTokenTests.swift, which re-runs it in-process and
// fails if the checked-in Swift no longer matches the JSON. A test asserts the two
// copies are textually identical, so the mirror cannot rot unnoticed.

import Foundation

// MARK: - generator core (BEGIN mirrored region)

struct DesignToken: Decodable {
    let name: String
    let type: String
    let value: String
    let description: String
}

struct DesignTokenFile: Decodable {
    struct ContentHash: Decodable { let tokens: String }
    let contentHash: ContentHash
    let tokens: [DesignToken]
}

enum TokenGenerator {
    /// Paper token types, in the order their groups are emitted. A type absent from
    /// this table is deliberately not a constant — see `skipReasons`.
    static let groups: [(type: String, namespace: String, heading: String)] = [
        ("color", "Color", "Colour"),
        ("fontSize", "Size", "Type sizes"),
        ("lineHeight", "Leading", "Leading"),
        ("spacing", "Space", "Spacing"),
        ("radius", "Radius", "Radius"),
        ("container", "Container", "Containers"),
    ]

    /// Tokens that exist in the export but must not become a constant here, with the
    /// reason each one is out — the reasons are printed into the generated header so a
    /// reader does not have to guess whether a missing token was an oversight.
    static let skipReasons: [(subject: String, reason: String)] = [
        (
            "--radius-full",
            "9999px is Paper's spelling of calc(infinity * 1px). The board says to use a capsule shape in Swift, and a 9999 constant would only invite someone to pass it to cornerRadius."
        ),
        (
            "--font-*, --font-weight-*, --tracking-*",
            "Typography.swift owns them: a weight is a font-file lookup and an em of tracking is a per-size point conversion, neither of which is a raw number."
        ),
    ]

    static func swiftSource(from data: Data) throws -> String {
        let file = try JSONDecoder().decode(DesignTokenFile.self, from: data)
        var out = header(for: file)

        for group in groups {
            let tokens = file.tokens.filter { $0.type == group.type && !isSkipped($0) }
            guard !tokens.isEmpty else { continue }
            out += "\n// MARK: - \(group.heading)\n\nextension DS {\n    enum \(group.namespace) {\n"
            out += tokens.map { declaration(for: $0) }.joined(separator: "\n")
            out += "    }\n}\n"
        }
        return out
    }

    static func isSkipped(_ token: DesignToken) -> Bool { token.name == "--radius-full" }

    static func header(for file: DesignTokenFile) -> String {
        var out = """
        // Generated by scripts/generate-tokens.swift — do not edit by hand.
        //
        // Source:       design/tokens.json
        // contentHash:  \(file.contentHash.tokens) (Paper's own, over the token set)
        // Tokens read:  \(file.tokens.count)
        //
        // Every doc comment below is the designer's verbatim token description. They are
        // the rules the values exist to serve, so they travel with the values.
        //
        // Not emitted:

        """
        for skip in skipReasons {
            out += "//   \(skip.subject)\n"
            out += wrap(skip.reason, prefix: "//     ")
        }
        out += """
        //

        import SwiftUI

        /// The design system's namespace. Caseless by construction — every member is a
        /// constant, and there is no such thing as an instance of the design system.
        enum DS {}

        """
        return out
    }

    static func declaration(for token: DesignToken) -> String {
        var out = wrap(token.description, prefix: "        /// ")
        out += "        ///\n"
        out += "        /// `\(token.name)` \(token.value)\n"
        switch token.type {
        case "color":
            let (red, green, blue) = rgb(token.value)
            out += "        static let \(propertyName(token.name)) = SwiftUI.Color("
            out += ".sRGB, red: \(red) / 255, green: \(green) / 255, blue: \(blue) / 255, opacity: 1)\n"
        default:
            out += "        static let \(propertyName(token.name)): CGFloat = \(number(token.value))\n"
        }
        return out
    }

    /// `--color-ink-secondary` -> `inkSecondary`, `--radius-3xl` -> `xxxl`,
    /// `--spacing-1` -> `s1`, `--text-body-lg` -> `bodyLarge`.
    static func propertyName(_ tokenName: String) -> String {
        var segments = tokenName.dropFirst(2).split(separator: "-").map(String.init)
        segments.removeFirst()
        segments = segments.enumerated().map { expand($0.element, isLeading: $0.offset == 0) }
        if segments.first?.allSatisfy(\.isNumber) == true { segments.insert("s", at: 0) }
        return segments.enumerated()
            .map { $0.offset == 0 ? $0.element : $0.element.prefix(1).uppercased() + $0.element.dropFirst() }
            .joined()
    }

    /// The two segment spellings that are not already words. `lg` is a scale step when it
    /// stands on its own (`--radius-lg`) but a modifier on a name when it trails one
    /// (`--text-body-lg`), and only the modifier reads wrong abbreviated. `2xl`/`3xl` is
    /// shorthand Swift cannot start an identifier with at all.
    static func expand(_ segment: String, isLeading: Bool) -> String {
        if segment == "lg", !isLeading { return "large" }
        if segment.count == 3, let repeats = Int(segment.prefix(1)), segment.dropFirst() == "xl" {
            return String(repeating: "x", count: repeats) + "l"
        }
        return segment
    }

    static func number(_ value: String) -> String {
        let scalar = Double(value.replacingOccurrences(of: "px", with: "")) ?? 0
        return scalar == scalar.rounded() ? String(Int(scalar)) : String(scalar)
    }

    /// sRGB channels straight off the hex, kept as `n / 255` so the literal can be read
    /// back against the export without a calculator.
    static func rgb(_ hex: String) -> (Int, Int, Int) {
        let digits = hex.dropFirst()
        let value = Int(digits, radix: 16) ?? 0
        return ((value >> 16) & 0xFF, (value >> 8) & 0xFF, value & 0xFF)
    }

    /// Hard-wraps a description to 96 columns so long rationales stay readable in the
    /// generated file. Deterministic: greedy, on spaces, no hyphenation.
    static func wrap(_ text: String, prefix: String, width: Int = 96) -> String {
        var lines: [String] = []
        var line = ""
        for word in text.split(separator: " ") {
            let candidate = line.isEmpty ? String(word) : line + " " + word
            if prefix.count + candidate.count > width, !line.isEmpty {
                lines.append(line)
                line = String(word)
            } else {
                line = candidate
            }
        }
        if !line.isEmpty { lines.append(line) }
        return lines.map { prefix + $0 + "\n" }.joined()
    }
}

// MARK: - generator core (END mirrored region)

let repoRoot = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
let arguments = Array(CommandLine.arguments.dropFirst())
let input = arguments.count > 0
    ? URL(fileURLWithPath: arguments[0])
    : repoRoot.appendingPathComponent("design/tokens.json")
let output = arguments.count > 1
    ? URL(fileURLWithPath: arguments[1])
    : repoRoot.appendingPathComponent("MathTutor/DesignSystem/Generated/DesignTokens.swift")

do {
    let source = try TokenGenerator.swiftSource(from: Data(contentsOf: input))
    try FileManager.default.createDirectory(
        at: output.deletingLastPathComponent(),
        withIntermediateDirectories: true
    )
    try source.write(to: output, atomically: true, encoding: .utf8)
    print("wrote \(output.path)")
} catch {
    FileHandle.standardError.write(Data("generate-tokens: \(error)\n".utf8))
    exit(1)
}
