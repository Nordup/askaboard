#!/usr/bin/env node
/**
 * Generate src/shared/hand-font.ts: the single-line handwriting font of the
 * live scenes (write() in a scene program). The source is the Hershey font data in
 * the hersheytext npm package (MIT; the Hershey fonts are public domain):
 *
 *   npm install --no-save hersheytext@2.0.0   (in a scratch folder)
 *   node scripts/lab/make-hand-font.mjs <scratch>/node_modules/hersheytext/hersheytext.json
 *
 * Latin, digits and ASCII signs come from "futural" (Sans 1-stroke), Greek
 * from "greek", maths signs from "mathlow". scripts/lab/hand-font-extra.mjs
 * adds Cyrillic, punctuation, arrows, more maths signs, special Latin letters
 * and the combining accents, as recipes on these strokes. Units: cap height 1,
 * baseline at y = 0, +y down. Each glyph is {a: advance, s: strokes as flat
 * [x, y, x, y, …]}; an alias is the character whose glyph it shares.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { extraGlyphs } from './hand-font-extra.mjs'

const source = process.argv[2]
if (!source) {
  console.error('usage: node scripts/lab/make-hand-font.mjs <path to hersheytext.json>')
  process.exit(1)
}
const fonts = JSON.parse(readFileSync(source, 'utf8'))
const BASE = 22
const CAP = 21
const r3 = (v) => Math.round(v * 1000) / 1000

/** chars[i] is the glyph of ASCII 33 + i. */
function glyph(font, key) {
  const entry = fonts[font].chars[key.charCodeAt(0) - 33]
  if (!entry) throw new Error(`${font} has no glyph for ${key}`)
  const strokes = []
  for (const part of (entry.d || '').split('M').map((s) => s.trim()).filter(Boolean)) {
    const nums = part.replace(/L/g, ' ').split(/[\s,]+/).filter(Boolean).map(Number)
    const flat = []
    for (let i = 0; i + 1 < nums.length; i += 2) flat.push(r3(nums[i] / CAP), r3((nums[i + 1] - BASE) / CAP))
    if (flat.length >= 2) strokes.push(flat)
  }
  return { a: r3((Number(entry.o) * 2) / CAP), s: strokes }
}

const out = {}
for (let code = 33; code <= 126; code++) out[String.fromCharCode(code)] = glyph('futural', String.fromCharCode(code))

const GREEK = {
  A: 'Α', B: 'Β', C: 'Χ', D: 'Δ', E: 'Ε', F: 'Φ', G: 'Γ', H: 'Η', I: 'Ι', K: 'Κ', L: 'Λ', M: 'Μ', N: 'Ν', O: 'Ο', P: 'Π', Q: 'Θ', R: 'Ρ', S: 'Σ', T: 'Τ', U: 'Υ', W: 'Ω', X: 'Ξ', Y: 'Ψ', Z: 'Ζ',
  a: 'α', b: 'β', c: 'χ', d: 'δ', e: 'ε', f: 'φ', g: 'γ', h: 'η', i: 'ι', k: 'κ', l: 'λ', m: 'μ', n: 'ν', o: 'ο', p: 'π', q: 'θ', r: 'ρ', s: 'σ', t: 'τ', u: 'υ', w: 'ω', x: 'ξ', y: 'ψ', z: 'ζ'
}
for (const [key, char] of Object.entries(GREEK)) out[char] = glyph('greek', key)

const MATH = {
  '!': '±', '"': '∓', '#': '×', $: '·', '&': '≤', "'": '≥', ':': '∏', ';': '∑', '?': '≠', '@': '≡', '^': '∝', _: '∞', '`': '°',
  b: '√', d: '⊂', e: '∪', f: '⊃', g: '∩', h: '∈', i: '→', j: '↑', k: '←', l: '↓', m: '∂', n: '∇', p: '∫', v: '∃', x: '÷', z: '⊥', '|': '∠', '~': '∴'
}
for (const [key, char] of Object.entries(MATH)) out[char] = glyph('mathlow', key)
// The minus sign is the hyphen, a little wider.
out['−'] = { a: out['-'].a, s: out['-'].s }
// ≈: two tildes, raised and lowered.
const tilde = out['~']
const shift = (strokes, dy) => strokes.map((flat) => flat.map((v, i) => (i % 2 ? r3(v + dy) : v)))
out['≈'] = { a: tilde.a, s: [...shift(tilde.s, -0.12), ...shift(tilde.s, 0.12)] }

// Vulgar fractions: a small raised numerator, a slash, a small denominator.
const place = (g, scale, dx, dy) => g.s.map((flat) => flat.map((v, i) => r3(i % 2 ? v * scale + dy : v * scale + dx)))
for (const [char, [n, d]] of Object.entries({ '½': ['1', '2'], '⅓': ['1', '3'], '⅔': ['2', '3'], '¼': ['1', '4'], '¾': ['3', '4'] })) {
  const small = 0.55
  const num = out[n]
  const den = out[d]
  const slash = out['/']
  const nw = num.a * small
  out[char] = {
    a: r3(nw * 1.45 + den.a * small),
    s: [...place(num, small, 0, -0.5), ...place(slash, 0.8, nw * 0.45, 0.04), ...place(den, small, nw * 1.45, 0.04)]
  }
}

const aliases = extraGlyphs(out)

const target = join(dirname(fileURLToPath(import.meta.url)), '../../src/shared/hand-font.ts')
const body = Object.entries(out)
  .map(([char, g]) => `  ${JSON.stringify(char)}: ${JSON.stringify(g)}`)
  .concat(Object.entries(aliases).map(([char, to]) => `  ${JSON.stringify(char)}: ${JSON.stringify(to)}`))
  .join(',\n')
writeFileSync(
  target,
  `/**
 * The single-line handwriting font of live scenes (write() in a scene program).
 * Generated by scripts/lab/make-hand-font.mjs from the Hershey font data of
 * the hersheytext npm package (MIT; the Hershey fonts are public domain).
 * Do not edit by hand. Units: cap height 1, baseline y = 0, +y down.
 * a: advance width; s: strokes, each a flat list [x, y, x, y, …]. A string
 * value is an alias: the character whose glyph it shares. Combining accents
 * (U+0300…) have advance 0; write() puts them on the base letter.
 */
export interface HandGlyph {
  a: number
  s: number[][]
}

export const HAND_FONT: Record<string, HandGlyph | string> = {
${body}
}
`
)
console.log(`wrote ${Object.keys(out).length} glyphs and ${Object.keys(aliases).length} aliases to ${target}`)
