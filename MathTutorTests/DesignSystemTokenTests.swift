// The generator's transform, mirrored verbatim out of scripts/generate-tokens.swift so the
// drift test can run it in-process — an iOS test bundle cannot shell out to `swift`.
// `testGeneratorCoreMatchesTheScript` asserts the two copies are identical text, so the
// mirror cannot silently rot.

// MARK: - generator core (BEGIN mirrored region)

struct DesignToken: Decodable {
    let name: String
    let type: String
    let value: String
    let description: String
}

struct DesignTokenFile: Decodable {
    struct ContentHash: Decodable { let tokens: String }
    let contentHash: ContentHash
    let tokens: [DesignToken]
}

enum TokenGenerator {
    /// Paper token types, in the order their groups are emitted. A type absent from
    /// this table is deliberately not a constant — see `skipReasons`.
    static let groups: [(type: String, namespace: String, heading: String)] = [
        ("color", "Color", "Colour"),
        ("fontSize", "Size", "Type sizes"),
        ("lineHeight", "Leading", "Leading"),
        ("spacing", "Space", "Spacing"),
        ("radius", "Radius", "Radius"),
        ("container", "Container", "Containers"),
    ]

    /// Tokens that exist in the export but must not become a constant here, with the
    /// reason each one is out — the reasons are printed into the generated header so a
    /// reader does not have to guess whether a missing token was an oversight.
    static let skipReasons: [(subject: String, reason: String)] = [
        (
            "--radius-full",
            "9999px is Paper's spelling of calc(infinity * 1px). The board says to use a capsule shape in Swift, and a 9999 constant would only invite someone to pass it to cornerRadius."
        ),
        (
            "--font-*, --font-weight-*, --tracking-*",
            "Typography.swift owns them: a weight is a font-file lookup and an em of tracking is a per-size point conversion, neither of which is a raw number."
        ),
    ]

    static func swiftSource(from data: Data) throws -> String {
        let file = try JSONDecoder().decode(DesignTokenFile.self, from: data)
        var out = header(for: file)

        for group in groups {
            let tokens = file.tokens.filter { $0.type == group.type && !isSkipped($0) }
            guard !tokens.isEmpty else { continue }
            out += "\n// MARK: - \(group.heading)\n\nextension DS {\n    enum \(group.namespace) {\n"
            out += tokens.map { declaration(for: $0) }.joined(separator: "\n")
            out += "    }\n}\n"
        }
        return out
    }

    static func isSkipped(_ token: DesignToken) -> Bool { token.name == "--radius-full" }

    static func header(for file: DesignTokenFile) -> String {
        var out = """
        // Generated by scripts/generate-tokens.swift — do not edit by hand.
        //
        // Source:       design/tokens.json
        // contentHash:  \(file.contentHash.tokens) (Paper's own, over the token set)
        // Tokens read:  \(file.tokens.count)
        //
        // Every doc comment below is the designer's verbatim token description. They are
        // the rules the values exist to serve, so they travel with the values.
        //
        // Not emitted:

        """
        for skip in skipReasons {
            out += "//   \(skip.subject)\n"
            out += wrap(skip.reason, prefix: "//     ")
        }
        out += """
        //

        import SwiftUI

        /// The design system's namespace. Caseless by construction — every member is a
        /// constant, and there is no such thing as an instance of the design system.
        enum DS {}

        """
        return out
    }

    static func declaration(for token: DesignToken) -> String {
        var out = wrap(token.description, prefix: "        /// ")
        out += "        ///\n"
        out += "        /// `\(token.name)` \(token.value)\n"
        switch token.type {
        case "color":
            let (red, green, blue) = rgb(token.value)
            out += "        static let \(propertyName(token.name)) = SwiftUI.Color("
            out += ".sRGB, red: \(red) / 255, green: \(green) / 255, blue: \(blue) / 255, opacity: 1)\n"
        default:
            out += "        static let \(propertyName(token.name)): CGFloat = \(number(token.value))\n"
        }
        return out
    }

    /// `--color-ink-secondary` -> `inkSecondary`, `--radius-3xl` -> `xxxl`,
    /// `--spacing-1` -> `s1`, `--text-body-lg` -> `bodyLarge`.
    static func propertyName(_ tokenName: String) -> String {
        var segments = tokenName.dropFirst(2).split(separator: "-").map(String.init)
        segments.removeFirst()
        segments = segments.enumerated().map { expand($0.element, isLeading: $0.offset == 0) }
        if segments.first?.allSatisfy(\.isNumber) == true { segments.insert("s", at: 0) }
        return segments.enumerated()
            .map { $0.offset == 0 ? $0.element : $0.element.prefix(1).uppercased() + $0.element.dropFirst() }
            .joined()
    }

    /// The two segment spellings that are not already words. `lg` is a scale step when it
    /// stands on its own (`--radius-lg`) but a modifier on a name when it trails one
    /// (`--text-body-lg`), and only the modifier reads wrong abbreviated. `2xl`/`3xl` is
    /// shorthand Swift cannot start an identifier with at all.
    static func expand(_ segment: String, isLeading: Bool) -> String {
        if segment == "lg", !isLeading { return "large" }
        if segment.count == 3, let repeats = Int(segment.prefix(1)), segment.dropFirst() == "xl" {
            return String(repeating: "x", count: repeats) + "l"
        }
        return segment
    }

    static func number(_ value: String) -> String {
        let scalar = Double(value.replacingOccurrences(of: "px", with: "")) ?? 0
        return scalar == scalar.rounded() ? String(Int(scalar)) : String(scalar)
    }

    /// sRGB channels straight off the hex, kept as `n / 255` so the literal can be read
    /// back against the export without a calculator.
    static func rgb(_ hex: String) -> (Int, Int, Int) {
        let digits = hex.dropFirst()
        let value = Int(digits, radix: 16) ?? 0
        return ((value >> 16) & 0xFF, (value >> 8) & 0xFF, value & 0xFF)
    }

    /// Hard-wraps a description to 96 columns so long rationales stay readable in the
    /// generated file. Deterministic: greedy, on spaces, no hyphenation.
    static func wrap(_ text: String, prefix: String, width: Int = 96) -> String {
        var lines: [String] = []
        var line = ""
        for word in text.split(separator: " ") {
            let candidate = line.isEmpty ? String(word) : line + " " + word
            if prefix.count + candidate.count > width, !line.isEmpty {
                lines.append(line)
                line = String(word)
            } else {
                line = candidate
            }
        }
        if !line.isEmpty { lines.append(line) }
        return lines.map { prefix + $0 + "\n" }.joined()
    }
}

// MARK: - generator core (END mirrored region)

final class DesignSystemTokenTests: XCTestCase {
    /// The checkout, found from this file rather than from the working directory — the
    /// simulator's cwd is `/` and says nothing about where the repo lives.
    private static let repoRoot = URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent()
        .deletingLastPathComponent()

    private static let exportURL = repoRoot.appendingPathComponent("design/tokens.json")
    private static let generatedURL = repoRoot
        .appendingPathComponent("MathTutor/DesignSystem/Generated/DesignTokens.swift")
    private static let scriptURL = repoRoot.appendingPathComponent("scripts/generate-tokens.swift")

    /// Source Sans 3's own vertical metrics, read out of the shipped `.otf` files: hhea
    /// ascender 1000, descender −326, line gap 0, against a 1000-unit em. Every leading
    /// expectation below is hand-computed from this one ratio.
    private static let sourceSans3LineHeightPerEm: CGFloat = 1.326

    override func setUp() {
        super.setUp()
        DS.Font.register()
    }

    // MARK: - Drift

    func testGeneratedTokensMatchTheExport() throws {
        let export = try Data(contentsOf: Self.exportURL)
        let expected = try TokenGenerator.swiftSource(from: export)
        let actual = try String(contentsOf: Self.generatedURL, encoding: .utf8)

        XCTAssertEqual(
            expected,
            actual,
            "DesignTokens.swift is out of date with design/tokens.json — run `swift scripts/generate-tokens.swift`."
        )
    }

    func testGeneratorCoreMatchesTheScript() throws {
        // Assembled rather than written whole so the sentinels appear in this file exactly
        // once each — as the real markers, not as a literal that would confuse the split.
        let begin = "// MARK: - generator core " + "(BEGIN mirrored region)"
        let end = "// MARK: - generator core " + "(END mirrored region)"

        func core(of source: String) throws -> String {
            let afterBegin = try XCTUnwrap(source.components(separatedBy: begin).dropFirst().first)
            return try XCTUnwrap(afterBegin.components(separatedBy: end).first)
        }

        let script = try String(contentsOf: Self.scriptURL, encoding: .utf8)
        let mirror = try String(contentsOfFile: #filePath, encoding: .utf8)

        XCTAssertEqual(
            try core(of: script),
            try core(of: mirror),
            "The mirrored generator core has diverged from scripts/generate-tokens.swift."
        )
    }

    func testRadiusFullIsNotEmittedAsANumber() throws {
        let generated = try String(contentsOf: Self.generatedURL, encoding: .utf8)

        // The header explains the omission in prose, so the check is on the declarations.
        XCTAssertFalse(
            generated.contains("CGFloat = 9999"),
            "--radius-full must be a capsule shape, not a constant."
        )
        XCTAssertFalse(generated.contains("static let full"))
        XCTAssertTrue(generated.contains("--radius-full"), "The header should say why it is missing.")
    }

    /// The header has to name the hash of the export it was actually generated from, so a
    /// reader can tell at a glance whether the Swift is downstream of the current design.
    ///
    /// Read from the export rather than written here as a literal. A hard-coded hash fails
    /// every time the design legitimately changes — which is precisely when the rest of this
    /// suite has something useful to say, and the last moment you want a spurious failure
    /// competing for attention.
    func testTheGeneratedHeaderNamesTheExportItCameFrom() throws {
        let export = try JSONDecoder().decode(
            DesignTokenFile.self,
            from: try Data(contentsOf: Self.exportURL)
        )
        let generated = try String(contentsOf: Self.generatedURL, encoding: .utf8)

        XCTAssertTrue(
            generated.contains(export.contentHash.tokens),
            """
            The generated file names a different contentHash than design/tokens.json does. \
            Re-run `swift scripts/generate-tokens.swift`.
            """
        )
    }

    func testGeneratorIsDeterministic() throws {
        let export = try Data(contentsOf: Self.exportURL)

        XCTAssertEqual(try TokenGenerator.swiftSource(from: export), try TokenGenerator.swiftSource(from: export))
    }

    // MARK: - One token of each type

    func testColourTokenResolvesToItsExportedHex() {
        // --color-brand #6051DC
        var red: CGFloat = 0
        var green: CGFloat = 0
        var blue: CGFloat = 0
        var alpha: CGFloat = 0
        UIColor(DS.Color.brand).getRed(&red, green: &green, blue: &blue, alpha: &alpha)

        XCTAssertEqual(red, 0x60 / 255, accuracy: 0.001)
        XCTAssertEqual(green, 0x51 / 255, accuracy: 0.001)
        XCTAssertEqual(blue, 0xDC / 255, accuracy: 0.001)
        XCTAssertEqual(alpha, 1, accuracy: 0.001)
    }

    func testScalarTokensResolveToTheirExportedValues() {
        XCTAssertEqual(DS.Size.body, 17)
        XCTAssertEqual(DS.Size.bodyLarge, 20)
        XCTAssertEqual(DS.Leading.body, 25)
        XCTAssertEqual(DS.Space.edge, 28)
        XCTAssertEqual(DS.Space.gap, 24)
        XCTAssertEqual(DS.Space.panelInset, 18)
        // The one layout value deliberately off the 4px grid.
        XCTAssertEqual(DS.Space.messageGap, 22)
        XCTAssertEqual(DS.Space.s7, DS.Space.edge)
        XCTAssertEqual(DS.Radius.lg, 14)
        XCTAssertEqual(DS.Radius.bubble, 18)
        XCTAssertEqual(DS.Radius.xxl, 20)
        XCTAssertEqual(DS.Radius.xxxl, 28)
        XCTAssertEqual(DS.Container.screen, 1376)
        XCTAssertEqual(DS.Container.rail, 72)
        XCTAssertEqual(DS.Container.panel, 337)
        XCTAssertEqual(DS.Container.panelContent, 301)
        XCTAssertEqual(DS.Container.column, 740)
    }

    // MARK: - Elevation

    func testElevationConvertsCSSBlurToASwiftUIShadowRadius() {
        // The port's most common failure: CSS blur is the Gaussian's full width, so every
        // radius here is half the number on the board.
        XCTAssertEqual(Elevation.canvasLift.shadowRadius, 3)
        XCTAssertEqual(Elevation.panelLift.shadowRadius, 5)
        XCTAssertEqual(Elevation.panelContact.shadowRadius, 1.5)
        XCTAssertEqual(Elevation.controlLift.shadowRadius, 3)
        XCTAssertEqual(Elevation.controlContact.shadowRadius, 1)
    }

    func testElevationLayersAreOuterLiftThenContactEdge() {
        XCTAssertEqual(Elevation.canvas.layers, [Elevation.canvasLift])
        XCTAssertEqual(Elevation.panel.layers, [Elevation.panelLift, Elevation.panelContact])
        XCTAssertEqual(Elevation.control.layers, [Elevation.controlLift, Elevation.controlContact])

        for level in Elevation.allCases {
            for layer in level.layers {
                XCTAssertGreaterThan(layer.y, 0, "Every offset on the board is y-only and downward.")
            }
            guard level.layers.count == 2 else { continue }
            XCTAssertGreaterThan(
                level.layers[0].blur,
                level.layers[1].blur,
                "The contact edge is the tighter of the two."
            )
        }
    }

    // MARK: - Layout arithmetic

    func testVerticalLanesDeriveFromTheStatusBarNotTheScreen() {
        XCTAssertEqual(ScreenLayout.statusBarBottom, ScreenLayout.statusBarY + ScreenLayout.statusBarHeight)
        XCTAssertEqual(ScreenLayout.statusBarBottom, 40)

        XCTAssertEqual(ScreenLayout.contentTop, ScreenLayout.statusBarBottom + DS.Space.edge)
        XCTAssertEqual(ScreenLayout.contentTop, 68)

        XCTAssertEqual(ScreenLayout.contentBottom, ScreenLayout.screenHeight - DS.Space.edge)
        XCTAssertEqual(ScreenLayout.contentBottom, 1004)

        XCTAssertEqual(ScreenLayout.contentHeight, ScreenLayout.screenHeight - ScreenLayout.contentTop - DS.Space.edge)
        XCTAssertEqual(ScreenLayout.contentHeight, 936)
        XCTAssertEqual(ScreenLayout.contentTop + ScreenLayout.contentHeight, ScreenLayout.contentBottom)
    }

    func testDockedHorizontalLanesFillTheScreenExactly() {
        XCTAssertEqual(ScreenLayout.boardX, ScreenLayout.railX + ScreenLayout.railWidth + DS.Space.gap)
        XCTAssertEqual(ScreenLayout.boardX, 124)

        let docked = ScreenLayout.screenWidth
            - DS.Space.edge - ScreenLayout.railWidth - DS.Space.gap - ScreenLayout.panelWidth - DS.Space.gap - DS.Space.edge
        XCTAssertEqual(ScreenLayout.boardWidthDocked, docked)
        XCTAssertEqual(ScreenLayout.boardWidthDocked, 863)

        XCTAssertEqual(ScreenLayout.panelX, ScreenLayout.boardX + ScreenLayout.boardWidthDocked + DS.Space.gap)
        XCTAssertEqual(ScreenLayout.panelX, ScreenLayout.screenWidth - DS.Space.edge - ScreenLayout.panelWidth)
        XCTAssertEqual(ScreenLayout.panelX, 1011)

        XCTAssertEqual(ScreenLayout.panelContentWidth, ScreenLayout.panelWidth - 2 * DS.Space.panelInset)
        XCTAssertEqual(ScreenLayout.panelContentWidth, 301)
    }

    func testCollapsedBoardAbsorbsTheGapAndThePanel() {
        XCTAssertEqual(ScreenLayout.boardWidthCollapsed, ScreenLayout.boardWidthDocked + DS.Space.gap + ScreenLayout.panelWidth)
        XCTAssertEqual(ScreenLayout.boardWidthCollapsed, 1224)
        XCTAssertEqual(ScreenLayout.boardX + ScreenLayout.boardWidthCollapsed, ScreenLayout.screenWidth - DS.Space.edge)
    }

    func testCollapsedDockIsInsetFromTheBoardNotTheScreen() {
        let boardRight = ScreenLayout.boardX + ScreenLayout.boardWidthCollapsed
        XCTAssertEqual(ScreenLayout.collapsedDockX, boardRight - DS.Space.gap - ScreenLayout.collapsedDockWidth)
        XCTAssertEqual(ScreenLayout.collapsedDockX, 1192)

        XCTAssertEqual(ScreenLayout.collapsedDockY, ScreenLayout.contentBottom - DS.Space.gap - ScreenLayout.collapsedDockHeight)
        XCTAssertEqual(ScreenLayout.collapsedDockY, 916)

        // The exception is the whole point: 24 from the board, not 28 from the screen.
        XCTAssertNotEqual(
            ScreenLayout.collapsedDockX,
            ScreenLayout.screenWidth - DS.Space.edge - ScreenLayout.collapsedDockWidth
        )
    }

    func testReadingColumnCentresPastThePeekNotOnTheScreen() {
        XCTAssertEqual(ScreenLayout.peekX, 0, "The board peek is flush left, with no edge inset.")

        let margin = (ScreenLayout.screenWidth - ScreenLayout.peekWidth - ScreenLayout.columnWidth) / 2
        XCTAssertEqual(ScreenLayout.columnMargin, margin)
        XCTAssertEqual(ScreenLayout.columnMargin, 284)

        XCTAssertEqual(ScreenLayout.columnX, ScreenLayout.peekWidth + margin)
        XCTAssertEqual(ScreenLayout.columnX, 352)
        XCTAssertEqual(ScreenLayout.columnX + ScreenLayout.columnWidth, 1092)

        XCTAssertNotEqual(ScreenLayout.columnX, (ScreenLayout.screenWidth - ScreenLayout.columnWidth) / 2)
    }

    // MARK: - Typography conversions

    func testTrackingConvertsFromEmToPoints() {
        // points = em × size. −0.01em at 40pt is −0.4pt, not −0.01pt.
        XCTAssertEqual(TextStyle.display.trackingPoints, -0.4, accuracy: 0.0001)
        XCTAssertEqual(TextStyle.title.trackingPoints, -0.26, accuracy: 0.0001)
        XCTAssertEqual(TextStyle.lead.trackingPoints, 0)
        XCTAssertEqual(TextStyle.body.trackingPoints, 0)
        XCTAssertEqual(TextStyle.label.trackingPoints, 0)
    }

    func testNaturalLineHeightMatchesTheFontsOwnMetrics() {
        for style in TextStyle.scale {
            XCTAssertEqual(
                style.naturalLineHeight,
                style.size * Self.sourceSans3LineHeightPerEm,
                accuracy: 0.01,
                "\(style.size)pt should draw a \(Self.sourceSans3LineHeightPerEm)em line box."
            )
        }
    }

    func testLineSpacingIsTheDesignLeadingMinusTheFontsOwnLineBox() {
        // lineSpacing = leading − naturalLineHeight, clamped at 0, hand-computed at 1.326em.
        let expected: [(TextStyle, CGFloat)] = [
            (.body, 25 - 17 * 1.326), // 2.458
            (.bodyCentred, 24 - 17 * 1.326), // 1.458
            (.chipPanel, 24 - 17 * 1.326), // 1.458
            (.lead, 30 - 21 * 1.326), // 2.154
            (.statusBar, 20 - 15 * 1.326), // 0.11
        ]
        for (style, spacing) in expected {
            XCTAssertEqual(style.lineSpacing, spacing, accuracy: 0.01)
        }

        for style in TextStyle.scale {
            XCTAssertEqual(style.lineSpacing, max(0, style.leading - style.uiFont.lineHeight), accuracy: 0.0001)
        }
    }

    func testStylesTighterThanTheFontClampToZeroAndCompensateInstead() {
        // Source Sans 3 draws taller than the design's line box for five of the ten styles.
        for style in [TextStyle.display, .title, .chipFullScreen, .bodyControl, .label] {
            XCTAssertEqual(style.lineSpacing, 0, "Cannot compress a line; the overhang moves to padding.")
            XCTAssertLessThan(style.lineBoxCompensation, 0)
        }

        // display: (48 − 40 × 1.326) ÷ 2 = −2.52
        XCTAssertEqual(TextStyle.display.lineBoxCompensation, (48 - 40 * 1.326) / 2, accuracy: 0.01)
        // body: (25 − 17 × 1.326) ÷ 2 = +1.229
        XCTAssertEqual(TextStyle.body.lineBoxCompensation, (25 - 17 * 1.326) / 2, accuracy: 0.01)

        for style in TextStyle.scale {
            XCTAssertEqual(
                style.naturalLineHeight + 2 * style.lineBoxCompensation,
                style.leading,
                accuracy: 0.0001,
                "A single line plus its compensation is exactly the design's line box."
            )
        }
    }

    // MARK: - The font itself

    func testSourceSans3ResolvesAsOneFamilyWithThreeWeights() throws {
        XCTAssertTrue(
            UIFont.familyNames.contains(DS.Font.family),
            "Registered families: \(UIFont.familyNames.filter { $0.contains("Source") })"
        )

        let members = UIFont.fontNames(forFamilyName: DS.Font.family)
        for weight in DS.FontWeight.allCases {
            XCTAssertTrue(
                members.contains(DS.Font.postScriptName(for: weight)),
                "\(DS.Font.postScriptName(for: weight)) missing from \(members)"
            )
        }
    }

    func testTheThreeRegisteredWeightsAre400And500And600AndAreDistinct() throws {
        XCTAssertEqual(DS.FontWeight.allCases.map(\.rawValue), [400, 500, 600])

        var normalised: [CGFloat] = []
        for weight in DS.FontWeight.allCases {
            let font = try XCTUnwrap(UIFont(name: DS.Font.postScriptName(for: weight), size: 17))
            XCTAssertEqual(font.fontName, DS.Font.postScriptName(for: weight))

            let traits = font.fontDescriptor.object(forKey: .traits) as? [UIFontDescriptor.TraitKey: Any]
            normalised.append(try XCTUnwrap(traits?[.weight] as? CGFloat))
        }

        // Three distinct faces, not the same file three times under different names.
        XCTAssertEqual(normalised, normalised.sorted())
        XCTAssertEqual(Set(normalised).count, 3, "Weights were \(normalised)")
    }

    func testRegisterIsSafeToCallAgain() {
        DS.Font.register()
        DS.Font.register()

        XCTAssertNotNil(UIFont(name: DS.Font.postScriptName(for: .semibold), size: 17))
    }

    func testTheScaleStaysInsideTheDesignsStatedLimits() {
        for style in TextStyle.scale {
            // "The smallest size in the product — nothing goes below this."
            XCTAssertGreaterThanOrEqual(style.size, DS.Size.label)
            // "The product never goes above semibold."
            XCTAssertLessThanOrEqual(style.weight.rawValue, DS.FontWeight.semibold.rawValue)
        }
    }
