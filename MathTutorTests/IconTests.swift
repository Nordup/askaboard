// The generator's transform, mirrored verbatim out of scripts/generate-icons.swift so the
// drift test can run it in-process — an iOS test bundle cannot shell out to `swift`.
// `testGeneratorCoreMatchesTheScript` asserts the two copies are identical text, so the
