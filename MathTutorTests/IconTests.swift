// MARK: - generator core (BEGIN mirrored region)

struct IconSpecFile: Decodable {
    struct Source: Decodable {
        let file: String
        let fileId: String
        let artboards: [String]
        let prose: [String]
    }

    struct Coverage: Decodable {
        struct Exclusion: Decodable {
            let name: String
            let reason: String
        }
        let productGlyphs: Int
        let excluded: [Exclusion]
    }

    struct Normalisation: Decodable {
        struct Exception: Decodable {
            let name: String
            let effectiveStrokeWidth: Double
            let reason: String
        }
        let targetEffectiveStrokeWidth: Double
        let rule: String
        let exceptions: [Exception]
    }

    let source: Source
    let coverage: Coverage
    let normalisation: Normalisation
    let icons: [IconSpec]
}

struct IconSpec: Decodable {
    struct ViewBox: Decodable {
        let width: Double
        let height: Double
    }

    struct Anomaly: Decodable {
        let instance: String
        let renderSize: Double
        let designStrokeWidth: Double
        let effectiveStrokeWidth: Double
        let note: String
    }

    let name: String
    let swiftCase: String
    let viewBox: ViewBox
    let productRenderSizes: [Double]
    let renderSize: Double
    let effectiveStrokeWidth: Double?
    let colorToken: String
    let dashTexture: String?
    let notes: String
    let designAnomaly: Anomaly?
    let elements: [IconElementSpec]
}

struct IconElementSpec: Decodable {
    let type: String
    let d: String?
    let x: Double?
    let y: Double?
    let width: Double?
    let height: Double?
    let rx: Double?
    let cx: Double?
    let cy: Double?
    let r: Double?
    let fill: String
    let stroke: String
    let strokeWidth: Double?
    let lineCap: String?
    let lineJoin: String?
    let dashArray: [Double]?
}

enum IconGenerator {
    /// The board's two named dash textures, mapped to the Swift cases that carry them.
    /// A texture absent from this table is a texture the port does not know about, and
    /// the generator refuses rather than dropping it silently.
    static let textures: [String: String] = [
        "dash/dotted": ".dotted",
        "dash/marching": ".marching",
    ]

    /// SVG's defaults, spelled out. An undeclared cap is `butt` and an undeclared join
    /// is `miter` — the design relies on both, so neither can be left to inference.
    static let caps: [String: String] = ["butt": ".butt", "round": ".round", "square": ".square"]
    static let joins: [String: String] = ["miter": ".miter", "round": ".round", "bevel": ".bevel"]

    enum Failure: Error, CustomStringConvertible {
        case unknownElement(String)
        case unknownTexture(String)
        case unknownLineStyle(String)

        var description: String {
            switch self {
            case .unknownElement(let type): "unknown element type \"\(type)\""
            case .unknownTexture(let name): "unknown dash texture \"\(name)\""
            case .unknownLineStyle(let name): "unknown cap or join \"\(name)\""
            }
        }
    }

    static func swiftSource(from data: Data) throws -> String {
        let file = try JSONDecoder().decode(IconSpecFile.self, from: data)
        var out = header(for: file)
        for icon in file.icons {
            let glyph = try declaration(for: icon, in: file)
            out += "\n" + glyph + "\n"
        }
        out += "\n" + dispatch(for: file) + "}\n"
        return out
    }

    static func header(for file: IconSpecFile) -> String {
        var out = """
        // Generated by scripts/generate-icons.swift — do not edit by hand.
        //
        // Source:   Paper file "\(file.source.file)"
        //           \(file.source.fileId)
        //
        """
        out += "\n"
        for artboard in file.source.artboards {
            out += wrap(artboard, prefix: "//           ")
        }
        out += "// Glyphs:   \(file.coverage.productGlyphs) product glyphs.\n"
        out += "// Prose:    \(file.source.prose.joined(separator: "\n//           "))\n"
        out += "//\n// Not here:\n"
        for exclusion in file.coverage.excluded {
            out += "//   \(exclusion.name)\n"
            out += wrap(exclusion.reason, prefix: "//     ")
        }
        out += """
        //
        // The `d` strings are the design's own, character for character, so this file can be
        // diffed straight against the Paper markup. Nothing here was redrawn, rounded, or
        // tidied; where a coordinate looks odd it is odd in the design too.
        //
        // The types live in Icon.swift. This file is data.

        import CoreGraphics

        enum IconPaths {

        """
        return out
    }

    static func declaration(for icon: IconSpec, in file: IconSpecFile) throws -> String {
        var out = wrap(headline(for: icon), prefix: "    /// ")
        out += "    ///\n"
        out += wrap(icon.notes, prefix: "    /// ")
        out += "    static let \(icon.swiftCase) = IconGlyph(\n"
        out += "        name: \(quoted(icon.name)),\n"
        out += "        viewBox: CGSize(width: \(number(icon.viewBox.width)), "
        out += "height: \(number(icon.viewBox.height))),\n"
        out += "        renderSize: \(number(icon.renderSize)),\n"
        out += "        productRenderSizes: [\(icon.productRenderSizes.map(number).joined(separator: ", "))],\n"

        if let exception = file.normalisation.exceptions.first(where: { $0.name == icon.name }) {
            out += wrap(
                "Exception to the \(decimal(file.normalisation.targetEffectiveStrokeWidth)) rule, "
                    + "kept deliberately. \(exception.reason)",
                prefix: "        // "
            )
        }
        var weight = icon.effectiveStrokeWidth
        if weight == nil {
            out += wrap("Nothing is stroked here, so this value is never read.", prefix: "        // ")
            weight = file.normalisation.targetEffectiveStrokeWidth
        }
        out += "        strokeWidth: \(number(weight ?? 0)),\n"
        out += "        colorToken: \(quoted(icon.colorToken)),\n"
        out += anomaly(for: icon)
        out += "        elements: [\n"
        for element in icon.elements {
            out += try declaration(for: element, texture: icon.dashTexture)
        }
        out += "        ]\n"
        out += "    )\n"
        return out
    }

    /// The one-line summary that opens each glyph's doc comment.
    static func headline(for icon: IconSpec) -> String {
        var sizes = "renders \(number(icon.renderSize))"
        if icon.productRenderSizes.count > 1 {
            let drawn = icon.productRenderSizes.map(number).joined(separator: ", ")
            sizes += " (product draws it at \(drawn))"
        }
        let weight = icon.effectiveStrokeWidth.map { "\(decimal($0))pt effective stroke" } ?? "fill only"
        return "`\(icon.name)` — \(sizes) on a \(number(icon.viewBox.width))×"
            + "\(number(icon.viewBox.height)) viewBox, \(weight), \(icon.colorToken)."
    }

    /// A defect in the design, carried into the code rather than quietly corrected.
    /// Recording it is what lets a test pin the current value, so that fixing it
    /// upstream shows up as a failing expectation instead of a silent change.
    static func anomaly(for icon: IconSpec) -> String {
        guard let anomaly = icon.designAnomaly else { return "" }
        var out = "        designAnomaly: IconAnomaly(\n"
        out += "            instance: \(quoted(anomaly.instance)),\n"
        out += "            renderSize: \(number(anomaly.renderSize)),\n"
        out += "            designStrokeWidth: \(number(anomaly.designStrokeWidth)),\n"
        out += "            effectiveStrokeWidth: \(number(anomaly.effectiveStrokeWidth)),\n"
        out += "            note: \(quoted(anomaly.note))\n"
        out += "        ),\n"
        return out
    }

    static func declaration(for element: IconElementSpec, texture: String?) throws -> String {
        var out = "            IconElement(\n"
        out += "                geometry: \(try geometry(of: element)),\n"
        out += "                isFilled: \(element.fill != "none"),\n"
        out += "                isStroked: \(element.stroke != "none"),\n"
        out += "                lineCap: \(try style(element.lineCap, in: caps, default: "butt")),\n"
        out += "                lineJoin: \(try style(element.lineJoin, in: joins, default: "miter")),\n"
        out += "                dash: \(try dash(of: element, texture: texture)),\n"
        out += "                designStrokeWidth: \(element.strokeWidth.map(number) ?? "nil")\n"
        out += "            ),\n"
        return out
    }

    static func geometry(of element: IconElementSpec) throws -> String {
        switch element.type {
        case "path":
            return ".path(\(quoted(element.d ?? "")))"
        case "rect":
            return ".rect(x: \(number(element.x ?? 0)), y: \(number(element.y ?? 0)), "
                + "width: \(number(element.width ?? 0)), height: \(number(element.height ?? 0)), "
                + "cornerRadius: \(number(element.rx ?? 0)))"
        case "circle":
            return ".circle(centerX: \(number(element.cx ?? 0)), centerY: \(number(element.cy ?? 0)), "
                + "radius: \(number(element.r ?? 0)))"
        default:
            throw Failure.unknownElement(element.type)
        }
    }

    static func dash(of element: IconElementSpec, texture: String?) throws -> String {
        guard element.dashArray != nil else { return "nil" }
        guard let texture, let swiftCase = textures[texture] else {
            throw Failure.unknownTexture(texture ?? "none declared on the glyph")
        }
        return swiftCase
    }

    static func style(_ declared: String?, in table: [String: String], default fallback: String) throws -> String {
        let name = declared ?? fallback
        guard let swiftCase = table[name] else { throw Failure.unknownLineStyle(name) }
        return swiftCase
    }

    static func dispatch(for file: IconSpecFile) -> String {
        var out = """
            /// Every glyph, by case.
            ///
            /// A switch and not a dictionary: adding a case to `Icon` without adding its
            /// geometry here fails the build rather than rendering a blank slot.
            static func glyph(for icon: Icon) -> IconGlyph {
                switch icon {

        """
        for icon in file.icons {
            out += "        case .\(icon.swiftCase): Self.\(icon.swiftCase)\n"
        }
        out += "        }\n    }\n"
        return out
    }

    /// `28.0` -> `28`, `2.18` -> `2.18`. Swift reads an integral literal as a `CGFloat`
    /// happily, and a trailing `.0` on every coordinate would bury the ones that matter.
    static func number(_ value: Double) -> String {
        value == value.rounded() ? String(Int(value)) : String(value)
    }

    /// One decimal place, for prose where `2` would read as an integer count rather than
    /// a stroke weight.
    static func decimal(_ value: Double) -> String {
        String(format: "%.1f", value)
    }

    static func quoted(_ text: String) -> String {
        "\"" + text.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\""
    }

    /// Hard-wraps to 96 columns so long rationales stay readable in the generated file.
    /// Deterministic: greedy, on spaces, no hyphenation.
    static func wrap(_ text: String, prefix: String, width: Int = 96) -> String {
        var lines: [String] = []
        var line = ""
        for word in text.split(separator: " ") {
            let candidate = line.isEmpty ? String(word) : line + " " + word
            if prefix.count + candidate.count > width, !line.isEmpty {
                lines.append(line)
                line = String(word)
            } else {
                line = candidate
            }
        }
        if !line.isEmpty { lines.append(line) }
        return lines.map { prefix + $0 + "\n" }.joined()
    }
}

// MARK: - generator core (END mirrored region)

/// These are transcription tests, not rendering tests. They ask one question over
/// and over: does the checked-in geometry still say what the design says? A glyph
/// that parses to nothing, spills out of its own viewBox, or quietly loses one of
/// the two deliberate stroke-weight exceptions is a bad export, and a bad export
/// looks exactly like a working build until someone sees it on a device.
final class IconTests: XCTestCase {
    /// `tool/pen`'s cap is drawn as a rounded corner on a rotated rectangle, and
    /// the round reaches x = 28.277 on a 28 viewBox. That is in the design, not in
    /// this port: an SVG viewport clips the 0.28pt sliver and so does `IconView`.
    /// Transcribe, never redraw — so the allowance is named rather than the
    /// coordinate being nudged.
    private static let documentedOverflow: [Icon: CGFloat] = [.toolPen: 0.3]

    /// The checkout, found from this file rather than from the working directory — the
    /// simulator's cwd is `/` and says nothing about where the repo lives.
    private static let repoRoot = URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent()
        .deletingLastPathComponent()

    private static let exportURL = repoRoot.appendingPathComponent("design/icons.json")
    private static let generatedURL = repoRoot
        .appendingPathComponent("MathTutor/DesignSystem/Generated/IconPaths.swift")
    private static let scriptURL = repoRoot.appendingPathComponent("scripts/generate-icons.swift")

    private func tightBounds(_ path: Path) -> CGRect { path.cgPath.boundingBoxOfPath }

    /// The union of every element, in viewBox coordinates.
    private func glyphBounds(_ icon: Icon) -> CGRect {
        icon.glyph.elements.reduce(CGRect.null) { union, element in
            union.union(tightBounds(element.path))
        }
    }

    // MARK: - Drift

    func testGeneratedIconPathsMatchTheExport() throws {
        let export = try Data(contentsOf: Self.exportURL)
        let expected = try IconGenerator.swiftSource(from: export)
        let actual = try String(contentsOf: Self.generatedURL, encoding: .utf8)

        XCTAssertEqual(
            expected,
            actual,
            "IconPaths.swift is out of date with design/icons.json — run `swift scripts/generate-icons.swift`."
        )
    }

    func testGeneratorCoreMatchesTheScript() throws {
        // Assembled rather than written whole so the sentinels appear in this file exactly
        // once each — as the real markers, not as a literal that would confuse the split.
        let begin = "// MARK: - generator core " + "(BEGIN mirrored region)"
        let end = "// MARK: - generator core " + "(END mirrored region)"

        func core(of source: String) throws -> String {
            let afterBegin = try XCTUnwrap(source.components(separatedBy: begin).dropFirst().first)
            return try XCTUnwrap(afterBegin.components(separatedBy: end).first)
        }

        let script = try String(contentsOf: Self.scriptURL, encoding: .utf8)
        let mirror = try String(contentsOfFile: #filePath, encoding: .utf8)

        XCTAssertEqual(
            try core(of: script),
            try core(of: mirror),
            "The mirrored generator core has diverged from scripts/generate-icons.swift."
        )
    }

    func testGeneratorIsDeterministic() throws {
        let export = try Data(contentsOf: Self.exportURL)

        XCTAssertEqual(try IconGenerator.swiftSource(from: export), try IconGenerator.swiftSource(from: export))
    }

    /// The export drives the enum, so the two must agree case for case. A glyph added
    /// to the JSON without a case — or the reverse — should fail here rather than in
    /// whichever screen was supposed to use it.
    func testEveryExportedGlyphHasACase() throws {
        let export = try JSONDecoder().decode(IconSpecFile.self, from: Data(contentsOf: Self.exportURL))

        XCTAssertEqual(export.coverage.productGlyphs, export.icons.count)
        XCTAssertEqual(export.icons.count, Icon.allCases.count)
        XCTAssertEqual(export.icons.map(\.name), Icon.allCases.map(\.rawValue))
    }

    /// The OS-chrome pair must not creep back in through a re-export.
    func testTheExportStillExcludesOSChrome() throws {
        let export = try JSONDecoder().decode(IconSpecFile.self, from: Data(contentsOf: Self.exportURL))

        XCTAssertEqual(export.coverage.excluded.map(\.name), ["os/wifi", "os/battery"])
        XCTAssertTrue(export.icons.allSatisfy { !$0.name.hasPrefix("os/") })
    }

    // MARK: - Completeness

    func testEveryCaseResolvesToNonEmptyGeometry() {
        for icon in Icon.allCases {
            let glyph = icon.glyph
            XCTAssertEqual(glyph.name, icon.rawValue, "\(icon) is wired to the wrong glyph")
            XCTAssertFalse(glyph.elements.isEmpty, "\(icon.rawValue) has no elements")

            for (index, element) in glyph.elements.enumerated() {
                let path = element.path
                XCTAssertFalse(path.isEmpty, "\(icon.rawValue) element \(index) parsed to nothing")
                XCTAssertTrue(
                    element.isFilled || element.isStroked,
                    "\(icon.rawValue) element \(index) is neither filled nor stroked"
                )
            }
        }
    }

    /// The board heads its OS section "DO NOT SHIP". Sixteen product glyphs on board
    /// 04 plus the four the states boards added, plus `ui/chevron-down` from the settings
    /// redesign — and `ui/selection-marker` is one case with two colour states rather than
    /// two cases — copy-pasting it is exactly how the design file ended up with a grey glyph
    /// whose markup claimed to be violet. `ui/check` and `ui/cross` are the same story with
    /// the evaluation pair.
    ///
    /// `ui/chevron-down` has no specimen on board 04, and neither do four of its predecessors:
    /// `ui/check`, `ui/cross` and `ui/retry` were read off boards 13 and 14, and
    /// `control/settings` off board 11. Board 04 is *"the original sixteen"*, not the set.
    /// `design/icons.json` is the source of truth and names the board each glyph came from.
    /// `ui/sidebar-toggle` is the twenty-seventh and arrived the same way: board 17 takes the
    /// gear out of the chat header and puts this in the slot it leaves, and it is drawn inside
    /// `btn/sidebar-toggle` rather than as a specimen.
    func testTheSetIsTheTwentySevenProductGlyphs() {
        XCTAssertEqual(Icon.allCases.count, 27)
        XCTAssertTrue(Icon.allCases.allSatisfy { !$0.rawValue.hasPrefix("os/") })
        XCTAssertEqual(Set(Icon.allCases.map(\.rawValue)).count, 27)
    }

    // MARK: - Transcription

    /// A mistyped coordinate almost always shows up as a glyph that no longer fits
    /// the box it was drawn in.
    func testEveryGlyphFitsInsideItsDeclaredViewBox() {
        for icon in Icon.allCases {
            let viewBox = icon.glyph.viewBox
            let bounds = glyphBounds(icon)
            let allowance = Self.documentedOverflow[icon] ?? 0.001

            XCTAssertGreaterThanOrEqual(bounds.minX, -allowance, "\(icon.rawValue) minX")
            XCTAssertGreaterThanOrEqual(bounds.minY, -allowance, "\(icon.rawValue) minY")
            XCTAssertLessThanOrEqual(bounds.maxX, viewBox.width + allowance, "\(icon.rawValue) maxX")
            XCTAssertLessThanOrEqual(bounds.maxY, viewBox.height + allowance, "\(icon.rawValue) maxY")
        }
    }

    /// The overflow above is a real property of the design, so it is asserted
    /// rather than merely tolerated: if a future export fixes the pen, this fails
    /// and the allowance goes away with it.
    func testToolPenOverflowsItsViewBoxExactlyAsTheDesignDoes() {
        let bounds = glyphBounds(.toolPen)

        XCTAssertEqual(bounds.maxX, 28.277, accuracy: 0.01)
        XCTAssertGreaterThan(bounds.maxX, Icon.toolPen.glyph.viewBox.width)
    }

    /// Every glyph should use most of its frame. A path that parsed to a fragment —
    /// an arc dropped, a subpath lost — still fits the viewBox, but it stops
    /// filling it. The floor is 0.4 rather than a half because two of the marks are
    /// genuinely small in their box: `ui/cross` spans 11.2 of 24 by design, and a
    /// checkmark is wider than it is tall.
    ///
    /// `ui/chevron-down` is the first mark the floor genuinely does not fit. It is 8 × 4 on a
    /// 16 box — half the width and a quarter of the height — because a disclosure caret is an
    /// intrinsically flat mark and a square viewBox is what keeps it centred in the row's
    /// 20pt slot. Redrawing it to fill two fifths vertically would make it a wedge, not a
    /// chevron. So its vertical floor is documented per-glyph rather than the shared one
    /// being lowered for everything — see `documentedFlatness`.
    func testEveryGlyphFillsItsFrame() {
        for icon in Icon.allCases {
            let viewBox = icon.glyph.viewBox
            let bounds = glyphBounds(icon)
            let verticalFloor = Self.documentedFlatness[icon] ?? 0.4

            XCTAssertGreaterThan(
                bounds.width / viewBox.width, 0.4,
                "\(icon.rawValue) covers less than two fifths of its viewBox horizontally"
            )
            XCTAssertGreaterThan(
                bounds.height / viewBox.height, verticalFloor,
                "\(icon.rawValue) is flatter than its documented floor of \(verticalFloor)"
            )
        }
    }

    /// Glyphs whose vertical extent is a property of the mark rather than a dropped subpath.
    /// Asserted rather than merely tolerated, exactly as `documentedOverflow` is: the floor is
    /// just under the real value, so a chevron that *did* lose an arm still fails.
    ///
    /// `ui/sidebar-toggle` is the second, and for the same kind of reason. It is two horizontal
    /// rules 6.5 apart on a 28 box — 0.23 — because it is drawn on the 28 grid the two layout
    /// controls beside it use, and it has to sit on their optical line rather than fill the
    /// box. Spreading the two lines to two fifths of 28 would make it a hamburger menu, which
    /// is a different control.
    static let documentedFlatness: [Icon: CGFloat] = [
        .uiChevronDown: 0.2,
        .uiSidebarToggle: 0.2,
    ]

    /// The allowance above is a real property of the design, so the shape it allows is pinned
    /// here — 8 × 4 on a 16 box, symmetric about the centre.
    func testTheChevronIsAsFlatAsTheDesignDraws() {
        let bounds = glyphBounds(.uiChevronDown)

        XCTAssertEqual(bounds.width, 8, accuracy: 0.01)
        XCTAssertEqual(bounds.height, 4, accuracy: 0.01)
        XCTAssertEqual(bounds.midX, 8, accuracy: 0.01, "centred horizontally in the 16 box")
    }

    /// The same, for the toggle: two lines, the top one 13 and the bottom one 8, left-aligned
    /// on x 4. The short second line is the whole mark — a pair of equal rules is a different
    /// glyph — so it is pinned rather than left to the bounding box, which cannot see it.
    func testTheSidebarToggleIsTwoLeftAlignedRulesWithAShortSecond() {
        let glyph = Icon.uiSidebarToggle.glyph

        XCTAssertEqual(glyph.elements.count, 2)
        XCTAssertEqual(glyph.elements[0].path.boundingRect.width, 13, accuracy: 0.01)
        XCTAssertEqual(glyph.elements[1].path.boundingRect.width, 8, accuracy: 0.01)
        XCTAssertEqual(glyph.elements[0].path.boundingRect.minX, 4, accuracy: 0.01)
        XCTAssertEqual(glyph.elements[1].path.boundingRect.minX, 4, accuracy: 0.01, "one left edge")

        // Both are exactly horizontal — a rule with any rise is a transcription slip the
        // bounding box of the pair would absorb.
        XCTAssertEqual(glyph.elements[0].path.boundingRect.height, 0, accuracy: 0.01)
        XCTAssertEqual(glyph.elements[1].path.boundingRect.height, 0, accuracy: 0.01)

        // Round caps, and it is what gives a 2pt rule its finished ends at 28.
        XCTAssertTrue(glyph.elements.allSatisfy { $0.lineCap == .round })
    }

    /// `control/full` is two opposite corner marks — variant C2 — and every part of that
    /// sentence is pinned: two elements, each an L of a 6-unit run and a 5.5-unit rise, at
    /// opposite corners of a 16 × 14 box centred in the 28 viewBox.
    ///
    /// The mark used to be the dock control's own 21 × 17 rect without a divider, which made the
    /// two controls in the header pair one outline with and without a line in it. The first
    /// redraw kept that box and read too big beside `ui/sidebar-toggle`; C2 pulls it in to
    /// 16 × 14. A bounding box cannot tell any of these apart on its own — the rect and the
    /// first redraw both measured 21 × 17 — so the corners are pinned by their own vertices.
    func testTheFullScreenControlIsTwoOppositeCornerMarks() {
        let glyph = Icon.controlFull.glyph

        XCTAssertEqual(glyph.elements.count, 2)
        for (index, element) in glyph.elements.enumerated() {
            let box = element.path.boundingRect
            XCTAssertEqual(box.width, 6, accuracy: 0.01, "element \(index) run")
            XCTAssertEqual(box.height, 5.5, accuracy: 0.01, "element \(index) rise")
        }

        // Top-right, then bottom-left: opposite corners of the 6…22 × 7…21 box.
        XCTAssertEqual(glyph.elements[0].path.boundingRect.maxX, 22, accuracy: 0.01)
        XCTAssertEqual(glyph.elements[0].path.boundingRect.minY, 7, accuracy: 0.01)
        XCTAssertEqual(glyph.elements[1].path.boundingRect.minX, 6, accuracy: 0.01)
        XCTAssertEqual(glyph.elements[1].path.boundingRect.maxY, 21, accuracy: 0.01)

        // The box is centred in the 28 viewBox on both axes — `28 − 22 == 6` and `28 − 21 == 7`
        // — so the mark is optically centred in its 32pt button without an offset.
        XCTAssertEqual(
            glyph.elements[0].path.boundingRect.maxX + glyph.elements[1].path.boundingRect.minX,
            28,
            accuracy: 0.01,
            "centred horizontally"
        )
        XCTAssertEqual(
            glyph.elements[0].path.boundingRect.minY + glyph.elements[1].path.boundingRect.maxY,
            28,
            accuracy: 0.01,
            "centred vertically"
        )

        // Three on-curve points each — a move, an H and a V. Two would be a dropped arm, and
        // the bounding box of an L cannot see the difference between an L and its diagonal.
        var counts: [Int] = []
        for element in glyph.elements {
            var count = 0
            element.path.forEach { _ in count += 1 }
            counts.append(count)
        }
        XCTAssertEqual(counts, [3, 3])

        // **Miter, not round.** A round join eats the corner mass, which is the whole of what
        // the mark is; the caps are round because the four ends are open.
        XCTAssertTrue(glyph.elements.allSatisfy { $0.lineJoin == .miter }, "MITER joins")
        XCTAssertTrue(glyph.elements.allSatisfy { $0.lineCap == .round })
        XCTAssertTrue(glyph.elements.allSatisfy { $0.isStroked && !$0.isFilled })
    }

    /// The bounding-box checks cannot see a dropped subpath in a mark whose two halves
    /// span the same box — lose one arm of `ui/cross` and it still measures 11.2 × 11.2.
    /// So the multi-subpath glyphs are counted, not measured.
    func testMultiSubpathGlyphsAreTranscribedWhole() {
        func points(_ icon: Icon, _ element: Int) -> Int {
            var count = 0
            icon.glyph.elements[element].path.forEach { _ in count += 1 }
            return count
        }

        // One path, two M subpaths — not two elements. Four on-curve points.
        XCTAssertEqual(Icon.uiCross.glyph.elements.count, 1)
        XCTAssertEqual(points(.uiCross, 0), 4)

        // A move and two implicit linetos: the design writes it without an L.
        XCTAssertEqual(points(.uiCheck, 0), 3)

        // The ring sweeps 315°, so it splits into four ≤90° cubics after the move.
        XCTAssertEqual(points(.uiRetry, 0), 5)
        XCTAssertEqual(points(.uiRetry, 1), 3)

        // The gear is a cog polygon plus a centre circle. Its teeth are geometry, not a
        // stroke effect, so a dropped one is a real transcription error the bounding box
        // cannot see: six teeth × 4 corners = 24, drawn as one move, 23 linetos and a close
        // that returns to the start without adding a corner of its own.
        XCTAssertEqual(Icon.controlSettings.glyph.elements.count, 2)
        XCTAssertEqual(points(.controlSettings, 0), 25)
    }

    // MARK: - Stroke normalisation

    /// The port adopts board 04's own un-applied recommendation: one weight, in
    /// points, applied after the viewBox is scaled, so it is the effective rendered
    /// weight at every size. The two documented exceptions survive that.
    func testStrokeWeightIsTwoPointsExceptForTheTwoDocumentedExceptions() {
        for icon in Icon.allCases {
            switch icon {
            case .toolLasso:
                // 98% of the dotted ring is gap, so perceived weight is dot
                // diameter, not line weight; normalising visibly dissolves it.
                XCTAssertEqual(icon.glyph.strokeWidth, 2.7, accuracy: 0.0001)
            case .boardHinge:
                // At 2.4 the frame closes on its six r=1 interior dots and the
                // mark reads as a blob at true size.
                XCTAssertEqual(icon.glyph.strokeWidth, 1.9, accuracy: 0.0001)
            default:
                XCTAssertEqual(
                    icon.glyph.strokeWidth, 2, accuracy: 0.0001,
                    "\(icon.rawValue) drifted off the 2.0 target"
                )
            }
        }
    }

    /// The set carries no design defect any more, and that is worth a test of its own.
    ///
    /// It used to: `control/settings` was a sliders mark drawn at 22 on a 28 viewBox with
    /// `stroke-width: 2.18`, rendering **1.71** against the set's 2.0 target, and its spec
    /// row was the one glyph row on board 14 missing the `→ 2.00` its three siblings carry.
    /// Redrawing it as a gear settled that in the design file — the chip instance now runs
    /// 2.545, which is exactly what renders 2.0 there — so the record went with it.
    ///
    /// This asserts the empty state rather than deleting the check, because an anomaly is
    /// something to add deliberately, not something that should quietly accumulate.
    func testNoGlyphCarriesARecordedAnomaly() {
        let flagged = Icon.allCases.filter { $0.glyph.designAnomaly != nil }

        XCTAssertEqual(flagged, [], "\(flagged.map(\.rawValue)) — record the reason, or fix the design")
    }

    /// The whole point of normalising in points rather than in viewBox units: the
    /// weight no longer depends on the size, which is what the design could not do
    /// in Paper. `composer/send` is the proof case — it needed 2.18 at 22pt and
    /// 1.85 at 26pt to render the same 2.0.
    func testStrokeWeightDoesNotDependOnRenderSize() {
        for size in [14, 20, 22, 24, 26, 28, 48] as [CGFloat] {
            XCTAssertEqual(Icon.composerSend.glyph.strokeWidth, 2, accuracy: 0.0001)
            XCTAssertEqual(Icon.chipExplain.glyph.strokeWidth, 2, accuracy: 0.0001)
            // The scale changes with the size; the weight deliberately does not.
            XCTAssertEqual(Icon.composerSend.scale(at: size), size / 24, accuracy: 0.0001)
        }
    }

    // MARK: - Dash textures

    /// Dash lengths are authored in viewBox units, so they have to be scaled with
    /// the path. Copied straight into a `StrokeStyle` they are right at exactly one
    /// size and wrong at every other — the lasso's dots would be the wrong size
    /// against an unchanged ring.
    func testDashPatternsScaleWithRenderSize() {
        // At its authored size the scale is 1 and the pattern is the design's own.
        XCTAssertEqual(Icon.toolLasso.dashPattern(at: 28) ?? [], [0.1, 4.3])
        XCTAssertEqual(Icon.uiSelectionMarker.dashPattern(at: 24) ?? [], [4.6, 3.9])

        // Half the size, half the dash.
        let halfLasso = Icon.toolLasso.dashPattern(at: 14) ?? []
        XCTAssertEqual(halfLasso.count, 2)
        XCTAssertEqual(halfLasso[0], 0.05, accuracy: 0.0001)
        XCTAssertEqual(halfLasso[1], 2.15, accuracy: 0.0001)

        // Twice the size, twice the dash.
        let doubleMarker = Icon.uiSelectionMarker.dashPattern(at: 48) ?? []
        XCTAssertEqual(doubleMarker.count, 2)
        XCTAssertEqual(doubleMarker[0], 9.2, accuracy: 0.0001)
        XCTAssertEqual(doubleMarker[1], 7.8, accuracy: 0.0001)

        // A gap-to-dot ratio that survives resizing is the property that matters:
        // it is what keeps the dotted ring reading as dots.
        for size in [14, 21, 28, 56] as [CGFloat] {
            let pattern = Icon.toolLasso.dashPattern(at: size) ?? []
            XCTAssertEqual(pattern[1] / pattern[0], 43, accuracy: 0.0001)
        }
    }

    func testOnlyTheTwoNamedGlyphsCarryADashTexture() {
        let dashed = Icon.allCases.filter { $0.dashPattern(at: 24) != nil }

        XCTAssertEqual(Set(dashed), [.toolLasso, .uiSelectionMarker])
        XCTAssertEqual(Icon.toolLasso.glyph.elements.first?.dash, .dotted)
        XCTAssertEqual(Icon.uiSelectionMarker.glyph.elements.first?.dash, .marching)
    }

    // MARK: - Rendering geometry

    func testShapeScalesTheViewBoxIntoTheRequestedSize() {
        let icon = Icon.uiSelectionMarker
        let element = icon.glyph.elements[0]
        let shape = IconElementShape(element: element, viewBox: icon.glyph.viewBox)

        // The marker's rect is 2.6…21.4 on a 24 viewBox. At 48 it doubles.
        let doubled = shape.path(in: CGRect(x: 0, y: 0, width: 48, height: 48)).cgPath.boundingBoxOfPath
        XCTAssertEqual(doubled.minX, 5.2, accuracy: 0.001)
        XCTAssertEqual(doubled.width, 37.6, accuracy: 0.001)

        // And it follows the rect it is given, so a caller can place it anywhere.
        let offset = shape.path(in: CGRect(x: 100, y: 50, width: 24, height: 24)).cgPath.boundingBoxOfPath
        XCTAssertEqual(offset.minX, 102.6, accuracy: 0.001)
        XCTAssertEqual(offset.minY, 52.6, accuracy: 0.001)
    }

    /// `board/hinge` is the one non-square product glyph. The board's rule: "a
    /// non-square mark centred in a square slot is correct, a stretched one is
    /// not." Given a square rect it must letterbox, never distort.
    func testNonSquareGlyphKeepsItsAspectRatio() {
        let icon = Icon.boardHinge
        XCTAssertEqual(icon.glyph.viewBox, CGSize(width: 26, height: 24))

        let shape = IconElementShape(element: icon.glyph.elements[0], viewBox: icon.glyph.viewBox)
        let square = shape.path(in: CGRect(x: 0, y: 0, width: 52, height: 52)).cgPath.boundingBoxOfPath

        // Scale is min(52/26, 52/24) = 2, and the mark is centred vertically in the
        // leftover 4pt rather than stretched to fill it.
        XCTAssertEqual(square.minX, 4.2, accuracy: 0.001)     // 2.1 × 2
        XCTAssertEqual(square.width, 43.6, accuracy: 0.001)   // 21.8 × 2
        XCTAssertEqual(square.height, 37.6, accuracy: 0.001)  // 18.8 × 2
        XCTAssertEqual(square.minY, 5.2 + 2, accuracy: 0.001) // 2.6 × 2, plus the 2pt letterbox
    }

